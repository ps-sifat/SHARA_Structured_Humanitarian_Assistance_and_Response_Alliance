const assert = require("node:assert/strict")

module.exports = async function languageFlows({ browser, base }) {
  const context = await browser.newContext({
    viewport: { width: 1440, height: 1000 },
  })
  const page = await context.newPage()
  const errors = []
  page.on("pageerror", (error) => errors.push(error.message))
  const go = async (path) => {
    await page.goto(`${base}/#${path}`)
    await page.locator("main").waitFor()
  }
  const choose = async (label) => {
    const option = page.getByRole("button", { name: label, exact: true })
    if (!await option.isVisible()) {
      await page.getByRole("button", { name: /^(Select language|ভাষা নির্বাচন করুন)$/ }).click()
    }
    await option.click()
  }
  const state = () =>
    page.evaluate(() => JSON.parse(localStorage.getItem("shara-demo-v1")))
  const login = async (id) => {
    await go("/login")
    await page.locator("#demo-account").selectOption(id)
    await page.getByRole("button", { name: "Continue", exact: true }).click()
  }
  try {
    await go("/")
    assert.equal(await page.locator("html").getAttribute("lang"), "bn")
    assert.equal(await page.getByRole("button", { name: "বাংলা", exact: true }).getAttribute("aria-pressed"), "true")
    await choose("English")
    await page.getByRole("heading", { name: "In times of crisis, we stand together" }).waitFor()
    assert.equal(await page.locator("html").getAttribute("lang"), "en")
    assert.equal(await page.getByRole("button", { name: "English", exact: true }).getAttribute("aria-pressed"), "true")
    assert.equal(await page.evaluate(() => localStorage.getItem("shara-language")), "en")
    assert.equal(await page.getByRole("group", { name: "Select language", exact: true }).count(), 1)
    await page.reload()
    await page.getByRole("heading", { name: "In times of crisis, we stand together" }).waitFor()

    await go("/apply")
    await page.locator("#district").click()
    await page.getByRole("textbox", { name: "Search", exact: true }).fill("sunamganj")
    await page.getByRole("button", { name: "Sunamganj", exact: true }).click()
    await page.locator("#upazila").click()
    await page.getByRole("button", { name: "Sunamganj Sadar", exact: true }).click()
    await page.locator("#people").fill("3")
    await page.getByRole("checkbox", { name: "Food", exact: true }).locator("..").click()
    assert.equal(await page.getByRole("checkbox").first().isChecked(), true)
    await choose("বাংলা")
    assert.match(await page.locator("#district").innerText(), /সুনামগঞ্জ/)
    assert.equal(await page.locator("#people").inputValue(), "3")
    assert.equal(await page.getByRole("checkbox").first().isChecked(), true)
    await choose("English")
    await page.getByRole("button", { name: "Submit request", exact: true }).click()
    await page.getByText("Enter a valid mobile number (e.g. 017XXXXXXXX)", { exact: true }).waitFor()
    await page.locator("#phone").fill("01700000000")
    await page.getByRole("button", { name: "Submit request", exact: true }).click()
    await page.getByRole("heading", { name: "Request received" }).waitFor()
    const request = (await state()).requests.at(-1)
    assert.equal(request.district, "সুনামগঞ্জ")
    assert.equal(request.upazila, "সুনামগঞ্জ সদর")
    assert.deepEqual(request.aid, ["খাদ্য"])
    const saved = JSON.stringify(await state())
    await choose("বাংলা")
    await choose("English")
    assert.equal(JSON.stringify(await state()), saved)

    await go(`/track?ref=${request.id}`)
    await page.locator("#track-code").fill(request.trackingCode)
    await page.getByRole("button", { name: "View progress", exact: true }).click()
    await page.getByText("Awaiting verification", { exact: true }).waitFor()
    assert.match(await page.locator("main").innerText(), /Sunamganj Sadar/)
    await choose("বাংলা")
    assert.equal(await page.locator("#track-code").inputValue(), request.trackingCode)
    await page.getByText("যাচাই অপেক্ষমাণ", { exact: true }).waitFor()
    await choose("English")

    await go("/map")
    await page.getByRole("textbox", { name: "Search district or upazila" }).fill("SUNAMGANJ")
    await page.getByRole("button", { name: /Sunamganj Sadar/ }).first().click()
    await page.getByRole("link", { name: "Request help in this area", exact: true }).click()
    assert.match(await page.locator("#district").innerText(), /Sunamganj/)
    assert.match(await page.locator("#upazila").innerText(), /Sunamganj Sadar/)

    await go("/volunteer/register")
    await page.locator("#v-name").fill("Fictional volunteer")
    await page.locator("#v-district").selectOption({ label: "Kurigram" })
    await page.locator("#v-upazila").selectOption({ label: "Kurigram Sadar" })
    assert.equal(await page.locator("#v-district").inputValue(), "কুড়িগ্রাম")
    await choose("বাংলা")
    assert.equal(await page.locator("#v-name").inputValue(), "Fictional volunteer")
    assert.equal(await page.locator("#v-district").inputValue(), "কুড়িগ্রাম")
    await choose("English")

    await login("a-admin")
    await page.getByRole("heading", { name: "Super admin overview", exact: true }).waitFor()
    await go("/admin/requests")
    await page.locator("#queue-district").selectOption({ label: "Sunamganj" })
    await page.waitForURL(/district=/)
    await page.waitForFunction(() => document.querySelector("#queue-district")?.value === "সুনামগঞ্জ")
    assert.equal(await page.locator("#queue-district").inputValue(), "সুনামগঞ্জ")
    await page.locator("#request-search").fill("Sunamganj")
    await page.waitForURL(/q=Sunamganj/)
    assert.ok(await page.getByRole("link", { name: "Review and assign a team", exact: true }).count() > 0)
    await go("/admin/suppliers")
    await page.getByRole("button", { name: "Add supplier", exact: true }).click()
    await page.getByRole("dialog").getByRole("button", { name: "Close", exact: true }).click()
    await login("a-org1")
    await go("/org/profile")
    await page.getByRole("button", { name: "Edit profile", exact: true }).click()
    await page.getByRole("dialog", { name: "Edit organization profile" }).waitFor()
    await page.keyboard.press("Escape")
    await login("a-v1")
    await go("/volunteer/profile/edit")
    await page.getByRole("heading", { name: "Profile and availability", exact: true }).waitFor()
    assert.equal(await page.locator("#v-district").inputValue(), "কুড়িগ্রাম")

    await go("/")
    for (const width of [320, 390]) {
      await page.setViewportSize({ width, height: 844 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
      assert.equal(await page.getByRole("group", { name: "Select language", exact: true }).count(), 0)
      const bounds = await page.getByRole("button", { name: "Select language", exact: true }).boundingBox()
      assert.ok(bounds.y < 100 && bounds.x >= 0 && bounds.x + bounds.width <= width)
    }
    await choose("বাংলা")
    await page.getByRole("button", { name: "ভাষা নির্বাচন করুন", exact: true }).click()
    await page.getByRole("button", { name: "English", exact: true }).focus()
    await page.keyboard.press("Enter")
    await page.getByRole("dialog", { name: "Select language", exact: true }).waitFor({ state: "hidden" })
    await page.getByRole("button", { name: "Open main menu", exact: true }).click()
    await page.getByRole("dialog", { name: "Main menu", exact: true }).getByRole("link", { name: "Request help", exact: true }).waitFor()
    await page.keyboard.press("Escape")
    await page.screenshot({ path: "/tmp/shara-english-mobile.png", fullPage: false })
    const second = await context.newPage()
    await second.goto(`${base}/#/privacy`)
    await second.getByRole("heading", { name: "Data and privacy", exact: true }).waitFor()
    await choose("বাংলা")
    await second.getByRole("heading", { name: "তথ্য ও গোপনীয়তা", exact: true }).waitFor()
    await second.close()
    await page.evaluate(() => localStorage.setItem("shara-language", "invalid"))
    await page.reload()
    await page.getByRole("heading", { name: "দুর্যোগে, মানুষের পাশে মানুষ", exact: true }).waitFor()
    assert.equal(await page.locator("html").getAttribute("lang"), "bn")
    await page.evaluate(() => {
      Storage.prototype.setItem = () => { throw new Error("Storage unavailable") }
    })
    await choose("English")
    await page.getByRole("heading", { name: "In times of crisis, we stand together", exact: true }).waitFor()
    assert.deepEqual(errors, [])
    console.log("PASS Bengali/English switching, translated forms and dashboards, bilingual search, canonical data, persistence, cross-tab sync, storage fallback and mobile keyboard access")
  } finally {
    await context.close()
  }
}
